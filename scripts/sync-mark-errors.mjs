// Copies the Heptapod mark's player and format from the studio repository into the app,
// along with a filtered error-only sequence deck (not the full 123-sequence library).
// Usage: node scripts/sync-mark-errors.mjs [mark directory]   (default: ../heptapod.studio/mark)
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = resolve(ROOT, 'resources/js/lib/mark-errors');
const COPIED = ['format.ts', 'player.ts'];

export const ERROR_SEQUENCE_IDS = [
    'glyphs-err',
    'display-check-error-word',
    'status-check-error',
    'status-failed',
    'patterns-seeded-flicker',
    'playful-slip',
];

/** Rewrite the studio's `.ts` import specifiers to extensionless bundler specifiers. */
export const rewriteImports = (source) =>
    source.replace(/(from '\.\.?\/[^']+)\.ts'/g, "$1'");

// The app's tsconfig enables noUncheckedIndexedAccess; keep patches minimal and behavior-neutral.
const PATCHES = {
    'player.ts': [
        [
            'play(sequence: Sequence, options: PlayOptions = {}): Promise<boolean> {',
            'async play(sequence: Sequence, options: PlayOptions = {}): Promise<boolean> {',
        ],
        [
            '  release(): Promise<boolean> {',
            '  async release(): Promise<boolean> {',
        ],
        [
            'gap: sequence.hold ? 0 : options.gap }',
            'gap: sequence.hold ? 0 : (options.gap ?? 0) }',
        ],
        [
            'points[index + 1].at - point.at > 1e-9',
            '(points[index + 1]?.at ?? point.at) - point.at > 1e-9',
        ],
    ],
};

function applyPatches(file, source) {
    let out = source;
    for (const [from, to] of PATCHES[file] ?? []) {
        const count = out.split(from).length - 1;
        if (count !== 1) {
            throw new Error(
                `sync-mark-errors: ${file} has ${count} matches for "${from}", expected 1`,
            );
        }
        out = out.replace(from, to);
    }
    return out;
}

function defaultMarkDirectory() {
    for (const candidate of [
        resolve(ROOT, '../heptapod.studio/mark'),
        // Linked worktrees live two levels deeper (.worktrees/<lane>).
        resolve(ROOT, '../../../heptapod.studio/mark'),
    ]) {
        if (existsSync(resolve(candidate, 'src/library.ts'))) {
            return candidate;
        }
    }
    return resolve(ROOT, '../heptapod.studio/mark');
}

export async function sync(mark) {
    const src = resolve(mark, 'src');
    await mkdir(OUT, { recursive: true });

    for (const file of COPIED) {
        const body = applyPatches(
            file,
            rewriteImports(await readFile(resolve(src, file), 'utf8')),
        );
        const header = `// Copied from heptapod.studio/mark/src/${file} by scripts/sync-mark-errors.mjs. Do not edit here.\n`;
        await writeFile(resolve(OUT, file), header + body, 'utf8');
    }

    const { library } = await import(
        pathToFileURL(resolve(src, 'library.ts')).href
    );
    const byId = new Map(library.map((sequence) => [sequence.id, sequence]));
    const selected = ERROR_SEQUENCE_IDS.map((id) => {
        const sequence = byId.get(id);
        if (!sequence) {
            throw new Error(
                `sync-mark-errors: missing sequence "${id}" in ${src}/library.ts`,
            );
        }
        return sequence;
    });

    const json = JSON.stringify(selected, null, 4);
    await writeFile(
        resolve(OUT, 'deck.ts'),
        [
            '// Generated by scripts/sync-mark-errors.mjs from heptapod.studio/mark/src/library.ts. Do not edit here.',
            "import type { Sequence } from './format';",
            '',
            `export const ERROR_DECK: readonly Sequence[] = ${json};`,
            '',
        ].join('\n'),
        'utf8',
    );

    return {
        selected: selected.map((sequence) => sequence.id),
        totalLibrary: library.length,
    };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const target = resolve(process.argv[2] ?? defaultMarkDirectory());
    const { selected, totalLibrary } = await sync(target);
    console.log(
        `synced ${selected.length} of ${totalLibrary} mark sequences into resources/js/lib/mark-errors/: ${selected.join(', ')}`,
    );
}
